/**
 * Server-only browser verification runner.
 *
 * Launches the installed system Chrome through Playwright, drives the real
 * `/demo` board the way a person would, and records what it observed as
 * assertions. It is deliberately narrow:
 *
 * - It only ever visits `DEMO_PATH` on the loopback origin it is given. The
 *   origin is validated with the same loopback rule the code-approval guard
 *   uses, and a client cannot supply it.
 * - It runs no shell command and executes nothing from the project: the only
 *   code that runs is the page under test, in a browser.
 * - It never writes application state, never requests a proposal and never
 *   applies a patch. It reads the page, and writes one screenshot to the
 *   evidence directory.
 *
 * Chrome is used through `channel: "chrome"` so no Playwright browser download
 * is required; a machine without Chrome reports `browser_unavailable` rather
 * than silently skipping verification.
 */

import { mkdir } from "node:fs/promises";
import path from "node:path";
import { chromium } from "@playwright/test";
import type { Page } from "@playwright/test";
import { TASKS_STORAGE_KEY } from "./tasks.ts";
import {
  VERIFICATION_LIMITS,
  VerificationError,
  countFailedAssertions,
  loopbackBaseUrl,
  type VerificationAssertion,
} from "./verification.ts";

/** The only path a verification run visits. */
export const DEMO_PATH = "/demo";

/** System Chrome, so no separate Playwright browser is downloaded. */
export const CHROME_CHANNEL = "chrome";

const STEP_TIMEOUT_MS = 15_000;
const SETTLE_TIMEOUT_MS = 5_000;

const TASK_TITLE = "Verify rename keeps completion";
const RENAMED_TITLE = "Verify rename keeps completion (renamed)";

const TASK_INPUT_PLACEHOLDER = "What needs to happen?";
/** The board's accessible completion counter. */
const COUNTER_SELECTOR = 'p[aria-live="polite"]';
const COUNTER_COMPLETE = "1 of 1 tasks complete.";
const CLEAN_BOARD = "no tasks on the board";

export type JourneyRunOptions = {
  /** Loopback origin of the running app. Validated before a browser starts. */
  baseUrl: string;
  /** Evidence file name stem. Generated by the server, never by a client. */
  runId: string;
  evidenceDir: string;
  now?: number;
};

export type JourneyOutcome = {
  expected: string;
  observed: string;
  assertions: VerificationAssertion[];
  url: string;
  durationMs: number;
  /** Evidence file name inside the evidence directory. */
  screenshot?: string;
};

export type VerificationRunner = (options: JourneyRunOptions) => Promise<JourneyOutcome>;

type Observation = { observed: string; passed: boolean; detail?: string };

function normalize(text: string | null | undefined): string {
  return (text ?? "").replace(/\s+/g, " ").trim();
}

function describeError(error: unknown): string {
  if (error instanceof Error) {
    return normalize(error.message).slice(0, 200) || error.name;
  }
  return "unknown error";
}

function toAssertion(
  id: string,
  label: string,
  expected: string,
  observation: Observation,
): VerificationAssertion {
  return {
    id,
    label,
    expected: normalize(expected).slice(0, VERIFICATION_LIMITS.textMax),
    observed:
      normalize(observation.observed).slice(0, VERIFICATION_LIMITS.textMax) || "not observed",
    passed: observation.passed,
    ...(observation.detail
      ? { detail: normalize(observation.detail).slice(0, VERIFICATION_LIMITS.textMax) }
      : {}),
  };
}

/**
 * Runs one check. A check that throws is recorded as a failed observation
 * rather than aborting the run, so a broken board still produces a verdict
 * instead of an error.
 */
async function check(
  steps: VerificationAssertion[],
  id: string,
  label: string,
  expected: string,
  run: () => Promise<Observation>,
): Promise<void> {
  try {
    steps.push(toAssertion(id, label, expected, await run()));
  } catch (error) {
    steps.push(
      toAssertion(id, label, expected, {
        observed: `the check could not be completed: ${describeError(error)}`,
        passed: false,
      }),
    );
  }
}

function allPassed(steps: readonly VerificationAssertion[]): boolean {
  return steps.every((step) => step.passed);
}

async function counterText(page: Page): Promise<string> {
  return normalize(await page.locator(COUNTER_SELECTOR).first().textContent());
}

async function checkboxChecked(page: Page): Promise<boolean> {
  return (await page.getByRole("checkbox").first().getAttribute("aria-checked")) === "true";
}

/**
 * Waits for the completion counter to reach an expected value, then reports
 * whatever is actually there. A timeout is not an error: the observed value is
 * exactly the evidence the verdict needs.
 */
async function settleCounter(page: Page, expected: string): Promise<string> {
  try {
    await page.waitForFunction(
      (input: { selector: string; text: string }) => {
        const node = document.querySelector(input.selector);
        return (node?.textContent ?? "").replace(/\s+/g, " ").trim() === input.text;
      },
      { selector: COUNTER_SELECTOR, text: expected },
      { timeout: SETTLE_TIMEOUT_MS },
    );
  } catch {
    // Report the value that was observed instead.
  }
  return counterText(page);
}

async function readStoredTasks(page: Page): Promise<{ raw: string | null; tasks: unknown[] }> {
  const raw = await page.evaluate(
    (key: string) => window.localStorage.getItem(key),
    TASKS_STORAGE_KEY,
  );
  if (raw === null) return { raw, tasks: [] };
  try {
    const parsed: unknown = JSON.parse(raw);
    return { raw, tasks: Array.isArray(parsed) ? parsed : [] };
  } catch {
    return { raw, tasks: [] };
  }
}

/**
 * Runs the verification journey against the demo task board.
 *
 * Expected: renaming a completed task keeps it complete, in the DOM and in the
 * persisted board state. The project's planted defect makes steps three to five
 * fail, which is the intended demonstration of a genuine failed verdict.
 */
export async function runDemoJourney(options: JourneyRunOptions): Promise<JourneyOutcome> {
  const origin = loopbackBaseUrl(options.baseUrl);

  const evidenceName = `${options.runId}.png`;
  if (!VERIFICATION_LIMITS.screenshotPattern.test(evidenceName)) {
    throw new VerificationError(
      "journey_failed",
      "The verification run id is not a safe evidence file name.",
    );
  }

  const url = new URL(DEMO_PATH, origin).toString();
  const started = Date.now();
  const steps: VerificationAssertion[] = [];
  let screenshot: string | undefined;

  let browser;
  try {
    browser = await chromium.launch({ channel: CHROME_CHANNEL, headless: true });
  } catch {
    throw new VerificationError(
      "browser_unavailable",
      "The verification browser could not be started. Google Chrome is required.",
    );
  }

  try {
    // A fresh context: the board starts from empty localStorage, and the run
    // cannot see or change a human's own board state.
    const context = await browser.newContext();
    const page = await context.newPage();
    page.setDefaultTimeout(STEP_TIMEOUT_MS);

    await page.goto(url, { waitUntil: "domcontentloaded" });

    await check(
      steps,
      "board-ready",
      "The demo board loads",
      `the add-task control is visible at ${DEMO_PATH}`,
      async () => {
        await page.getByPlaceholder(TASK_INPUT_PLACEHOLDER).waitFor({ state: "visible" });
        return { observed: "the add-task control is visible", passed: true };
      },
    );

    // Everything below depends on a usable board. When it did not load, the
    // run stops here and the single failed observation is the evidence.
    if (allPassed(steps)) {
      await check(
        steps,
        "task-created",
        "A task can be created",
        `1 task titled "${TASK_TITLE}"`,
        async () => {
          await page.getByPlaceholder(TASK_INPUT_PLACEHOLDER).fill(TASK_TITLE);
          await page.getByPlaceholder(TASK_INPUT_PLACEHOLDER).press("Enter");
          await page.getByText(TASK_TITLE, { exact: true }).waitFor({ state: "visible" });
          const rows = await page.getByRole("checkbox").count();
          return {
            observed: rows === 1 ? `1 task row, titled "${TASK_TITLE}"` : `${rows} task rows`,
            passed: rows === 1,
          };
        },
      );

      await check(
        steps,
        "marked-complete",
        "A task can be marked complete",
        `the checkbox is checked and the board reads "${COUNTER_COMPLETE}"`,
        async () => {
          await page.getByRole("checkbox").first().click();
          const counter = await settleCounter(page, COUNTER_COMPLETE);
          const checked = await checkboxChecked(page);
          return {
            observed: `the checkbox is ${checked ? "checked" : "unchecked"} and the board reads "${counter}"`,
            passed: checked && counter === COUNTER_COMPLETE,
          };
        },
      );

      await check(
        steps,
        "renamed",
        "The task can be renamed",
        `the row reads "${RENAMED_TITLE}"`,
        async () => {
          await page.getByRole("button", { name: `Edit "${TASK_TITLE}"` }).click();
          await page.locator('input[id^="edit-"]').fill(RENAMED_TITLE);
          await page.getByRole("button", { name: "Save" }).click();
          await page.getByText(RENAMED_TITLE, { exact: true }).waitFor({ state: "visible" });
          return { observed: `the row reads "${RENAMED_TITLE}"`, passed: true };
        },
      );

      await check(
        steps,
        "rename-keeps-completion",
        "Renaming a completed task keeps it complete",
        "the checkbox is still checked after the rename",
        async () => {
          const checked = await checkboxChecked(page);
          return {
            observed: `the checkbox is ${checked ? "still checked" : "unchecked"} after the rename`,
            passed: checked,
          };
        },
      );

      await check(
        steps,
        "rename-keeps-counter",
        "Renaming a completed task keeps the completion count",
        `the board still reads "${COUNTER_COMPLETE}"`,
        async () => {
          const counter = await counterText(page);
          return { observed: `the board reads "${counter}"`, passed: counter === COUNTER_COMPLETE };
        },
      );

      await check(
        steps,
        "completion-persists",
        "Completion survives a reload",
        `the renamed task is still complete in ${TASKS_STORAGE_KEY} after a reload`,
        async () => {
          await page.reload({ waitUntil: "domcontentloaded" });
          await page.getByText(RENAMED_TITLE, { exact: true }).waitFor({ state: "visible" });
          const { raw, tasks } = await readStoredTasks(page);
          const stored = tasks.find(
            (entry) =>
              typeof entry === "object" &&
              entry !== null &&
              (entry as { title?: unknown }).title === RENAMED_TITLE,
          ) as { completed?: unknown } | undefined;
          return {
            observed: `the reloaded board reports completed = ${String(stored?.completed)}`,
            passed: stored?.completed === true,
            detail: `localStorage["${TASKS_STORAGE_KEY}"] = ${raw ?? CLEAN_BOARD}`,
          };
        },
      );
    }

    await mkdir(options.evidenceDir, { recursive: true });
    await page.screenshot({
      path: path.join(options.evidenceDir, evidenceName),
      fullPage: true,
    });
    screenshot = evidenceName;
  } catch (error) {
    // An unexpected failure still yields evidence: whatever was observed.
    console.error(`[verification] journey aborted: ${describeError(error)}`);
    steps.push(
      toAssertion("journey-completed", "The verification journey completed", "every check ran", {
        observed: `the journey stopped early: ${describeError(error)}`,
        passed: false,
      }),
    );
  } finally {
    await browser.close().catch(() => {});
  }

  if (steps.length === 0) {
    throw new VerificationError("journey_failed", "The verification run produced no observations.");
  }

  const failed = countFailedAssertions(steps);
  return {
    expected: `Renaming a completed task keeps it complete, and the state survives a reload (driven at ${DEMO_PATH}).`,
    observed:
      failed === 0
        ? `Every check matched (${steps.length} of ${steps.length}).`
        : `${failed} of ${steps.length} checks did not match: ${steps
            .filter((step) => !step.passed)
            .map((step) => step.id)
            .join(", ")}.`,
    assertions: steps,
    url,
    durationMs: Date.now() - started,
    ...(screenshot ? { screenshot } : {}),
  };
}