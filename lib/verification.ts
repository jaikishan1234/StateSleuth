/**
 * Verification domain: the shape of a verdict, and the rule that decides it.
 *
 * Pure and I/O-free, and deliberately free of any browser import, so the rule
 * "a pass requires every check to pass" can be tested without launching Chrome.
 * The browser runner (lib/verification-browser.ts) produces the assertions;
 * this module judges them, and lib/workflow.ts refuses to record a pass that
 * this module did not call a pass.
 */

import { isLoopbackHostname } from "./local-guard.ts";

export const VERIFICATION_VERDICTS = ["passed", "failed"] as const;

export type VerificationVerdict = (typeof VERIFICATION_VERDICTS)[number];

/** One observation from a verification journey. */
export type VerificationAssertion = {
  id: string;
  label: string;
  expected: string;
  observed: string;
  passed: boolean;
  detail?: string;
};

/** The recorded outcome of a single verification run. */
export type VerificationResult = {
  verdict: VerificationVerdict;
  /** What the journey set out to prove, in one line. */
  expected: string;
  /** What the journey actually saw, in one line. */
  observed: string;
  steps: VerificationAssertion[];
  /** The page that was driven. Loopback only; never a client-supplied URL. */
  url: string;
  checkedAt: number;
  durationMs: number;
  /** Evidence file name inside the evidence directory, never a path. */
  screenshot?: string;
};

export const VERIFICATION_LIMITS = {
  stepCountMax: 40,
  textMax: 400,
  labelMax: 120,
  /** Evidence file names are generated by the server, never by a client. */
  screenshotPattern: /^[A-Za-z0-9_-]{1,64}\.png$/,
} as const;

export type VerificationErrorCode =
  | "invalid_url"
  | "not_local"
  | "browser_unavailable"
  | "journey_failed";

/** A verification failure that is safe to show. It never contains a secret. */
export class VerificationError extends Error {
  readonly code: VerificationErrorCode;

  constructor(code: VerificationErrorCode, message: string) {
    super(message);
    this.name = "VerificationError";
    this.code = code;
  }
}

function asText(value: unknown, max: number): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  if (trimmed.length === 0 || trimmed.length > max) return null;
  return trimmed;
}

function isAssertion(value: unknown): value is VerificationAssertion {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return false;
  const candidate = value as Record<string, unknown>;
  if (!asText(candidate.id, VERIFICATION_LIMITS.labelMax)) return false;
  if (!asText(candidate.label, VERIFICATION_LIMITS.labelMax)) return false;
  if (!asText(candidate.expected, VERIFICATION_LIMITS.textMax)) return false;
  if (!asText(candidate.observed, VERIFICATION_LIMITS.textMax)) return false;
  if (typeof candidate.passed !== "boolean") return false;
  if (candidate.detail !== undefined) {
    if (typeof candidate.detail !== "string" || candidate.detail.length > VERIFICATION_LIMITS.textMax) {
      return false;
    }
  }
  return true;
}

/**
 * Validates a stored verification result.
 *
 * Used by the workflow domain before it accepts a verdict, and by the store
 * when a record is read back, so a hand-edited file cannot introduce a pass
 * that no check supports.
 */
export function isStoredVerification(value: unknown): value is VerificationResult {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return false;
  const candidate = value as Record<string, unknown>;

  if (candidate.verdict !== "passed" && candidate.verdict !== "failed") return false;
  if (!asText(candidate.expected, VERIFICATION_LIMITS.textMax)) return false;
  if (!asText(candidate.observed, VERIFICATION_LIMITS.textMax)) return false;
  if (!asText(candidate.url, VERIFICATION_LIMITS.textMax)) return false;
  if (typeof candidate.checkedAt !== "number" || !Number.isFinite(candidate.checkedAt)) return false;
  if (typeof candidate.durationMs !== "number" || !Number.isFinite(candidate.durationMs)) return false;
  if (candidate.screenshot !== undefined) {
    if (typeof candidate.screenshot !== "string") return false;
    if (!VERIFICATION_LIMITS.screenshotPattern.test(candidate.screenshot)) return false;
  }

  if (!Array.isArray(candidate.steps)) return false;
  if (candidate.steps.length === 0 || candidate.steps.length > VERIFICATION_LIMITS.stepCountMax) {
    return false;
  }
  if (!candidate.steps.every(isAssertion)) return false;

  // A stored pass must be supported by the steps it carries.
  if (candidate.verdict === "passed" && !candidate.steps.every((step) => step.passed)) return false;

  return true;
}

/** A pass requires at least one check, and every check to pass. */
export function verdictFromAssertions(
  steps: readonly VerificationAssertion[],
): VerificationVerdict {
  return steps.length > 0 && steps.every((step) => step.passed) ? "passed" : "failed";
}

export function countFailedAssertions(steps: readonly VerificationAssertion[]): number {
  return steps.filter((step) => !step.passed).length;
}

/**
 * Normalises and validates the origin a verification run may drive.
 *
 * The journey only ever visits a fixed path on this origin, and only a
 * loopback origin is accepted, so a request cannot point the browser at an
 * arbitrary host. Any path, query or fragment on the input is discarded.
 */
export function loopbackBaseUrl(raw: string): string {
  let parsed: URL;
  try {
    parsed = new URL(raw);
  } catch {
    throw new VerificationError("invalid_url", "The verification base URL is not a valid URL.");
  }

  if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
    throw new VerificationError("invalid_url", "The verification base URL must use http or https.");
  }

  if (!isLoopbackHostname(parsed.hostname)) {
    throw new VerificationError(
      "not_local",
      "Verification only runs against a loopback origin (localhost or 127.0.0.1).",
    );
  }

  return parsed.origin;
}